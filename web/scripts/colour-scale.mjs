// Derives a 50–950 shade scale from one flag colour, keeping the flag's exact value at its anchor step.
// Run from web/: node scripts/colour-scale.mjs   (writes src/styles/colours/{biru,merah}.{css,ts})
import { writeFileSync } from "node:fs";

const SCALES = [
  { name: "biru", hex: "#000066", anchor: "800", note: "Jalur Gemilang blue; brand and interaction" },
  { name: "merah", hex: "#cc0000", anchor: "600", note: "Jalur Gemilang red; data emphasis" },
];
// Tailwind's lightness ladder, in OKLab L.
const STEPS = {
  50: 0.971,
  100: 0.936,
  200: 0.885,
  300: 0.808,
  400: 0.704,
  500: 0.637,
  600: 0.577,
  700: 0.505,
  800: 0.444,
  900: 0.396,
  950: 0.258,
};

const toLin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const fromLin = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
function hexToOklch(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => toLin(parseInt(hex.slice(i, i + 2), 16) / 255));
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s;
  const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s;
  const B = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
  return { L, C: Math.hypot(A, B), h: Math.atan2(B, A) };
}
function oklchToRgb({ L, C, h }) {
  const A = C * Math.cos(h),
    B = C * Math.sin(h);
  const l = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3;
  const m = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3;
  const s = (L - 0.0894841775 * A - 1.291485548 * B) ** 3;
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
}
const inGamut = (rgb) => rgb.every((c) => c >= -1e-4 && c <= 1 + 1e-4);
function toHex(lch) {
  let c = lch.C,
    rgb = oklchToRgb(lch);
  while (!inGamut(rgb) && c > 0) rgb = oklchToRgb({ ...lch, C: (c -= 0.002) });
  return (
    "#" +
    rgb
      .map((v) =>
        Math.round(fromLin(Math.min(1, Math.max(0, v))) * 255)
          .toString(16)
          .padStart(2, "0"),
      )
      .join("")
  );
}

for (const { name, hex, anchor, note } of SCALES) {
  const base = hexToOklch(hex);
  const T = STEPS[anchor];
  const scale = Object.fromEntries(
    Object.entries(STEPS).map(([step, t]) => {
      if (step === anchor) return [step, hex];
      const L = t > T ? base.L + ((t - T) * (0.971 - base.L)) / (0.971 - T) : base.L * (t / T);
      const C = base.C * (t > T ? (1 - L) / (1 - base.L) : 1);
      return [step, toHex({ L, C, h: base.h })];
    }),
  );
  const header = `/* Generated by scripts/colour-scale.mjs from ${hex} at ${anchor}: ${note}. */\n`;
  writeFileSync(
    `src/styles/colours/${name}.css`,
    header +
      "@theme {\n" +
      Object.entries(scale)
        .map(([k, v]) => `  --color-${name}-${k}: ${v};`)
        .join("\n") +
      "\n}\n",
  );
  writeFileSync(
    `src/styles/colours/${name}.ts`,
    `// Generated by scripts/colour-scale.mjs from ${hex} at ${anchor}: ${note}.\nexport const ${name} = {\n` +
      Object.entries(scale)
        .map(([k, v]) => `  "${k}": "${v}",`)
        .join("\n") +
      "\n};\n",
  );
  console.log(name, scale);
}
