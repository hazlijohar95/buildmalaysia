"""Outline "Build" in Cal Sans SemiBold for the Carta logo, and write the static font the OG images set text in.

Run from web/:  uv run --with fonttools --with brotli --with uharfbuzz python scripts/outline-wordmark.py

Writes src/brand/wordmark.ts (the outlined word, ink-normalised: top-left of the ink at 0,0) and
src/brand/og-font.ts (Cal Sans SemiBold as a static, subset TTF in base64 for the OG images: satori
cannot read woff2 or variable fonts, and inlining the bytes works the same in Node and on Workers).
"""

import base64
import io
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

WEB = Path(__file__).resolve().parent.parent
SOURCE = WEB / "src/assets/fonts/CalSansVF.woff2"
OG_FONT = WEB / "src/brand/og-font.ts"
OUT = WEB / "src/brand/wordmark.ts"

WORD = "Build"
WEIGHT = 600
TRACKING = -0.015  # em, as the site sets the wordmark

font = TTFont(SOURCE)
# Pin every axis, not only weight: a font with any axis left free is still variable, which satori cannot read.
axes = {a.axisTag: a.defaultValue for a in font["fvar"].axes} | {"wght": WEIGHT}
instantiateVariableFont(font, axes, inplace=True)
font.flavor = None
buf = io.BytesIO()
font.save(buf)
font = TTFont(io.BytesIO(buf.getvalue()))

# The OG images only set Latin text and figures, so the static font keeps Basic Latin, Latin-1 and punctuation.
static = TTFont(io.BytesIO(buf.getvalue()))
subsetter = Subsetter(Options(layout_features=["kern", "tnum", "lnum"]))
subsetter.populate(unicodes=[*range(0x20, 0x7F), *range(0xA0, 0x100), 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2212])
subsetter.subset(static)
out = io.BytesIO()
static.save(out)
OG_FONT.write_text(
    "// Generated by scripts/outline-wordmark.py: Cal Sans SemiBold (SIL OFL 1.1), static and subset. Do not edit by hand.\n"
    f'export const OG_FONT_BASE64 = "{base64.b64encode(out.getvalue()).decode()}";\n'
)

upem = font["head"].unitsPerEm
glyphs = font.getGlyphSet()

face = hb.Face(buf.getvalue())
hbfont = hb.Font(face)
hbbuf = hb.Buffer()
hbbuf.add_str(WORD)
hbbuf.guess_segment_properties()
hb.shape(hbfont, hbbuf, {"kern": True, "liga": False})

order = font.getGlyphOrder()
placed = []
pen_x = 0.0
for info, pos in zip(hbbuf.glyph_infos, hbbuf.glyph_positions):
    placed.append((order[info.codepoint], pen_x + pos.x_offset))
    pen_x += pos.x_advance + TRACKING * upem

bounds = BoundsPen(glyphs)
for name, x in placed:
    glyphs[name].draw(TransformPen(bounds, (1, 0, 0, -1, x, 0)))
min_x, min_y, max_x, max_y = bounds.bounds

svg = SVGPathPen(glyphs, ntos=lambda v: f"{round(v, 1):g}")
for name, x in placed:
    glyphs[name].draw(TransformPen(svg, (1, 0, 0, -1, x - min_x, -min_y)))

OUT.write_text(
    "// Generated by scripts/outline-wordmark.py from Cal Sans SemiBold. Do not edit by hand.\n"
    f"// Font units ({upem} per em), ink-normalised so the top-left of the ink is at 0,0 and the baseline at `height`.\n"
    "export const WORDMARK = {\n"
    f"  unitsPerEm: {upem},\n"
    f"  width: {round(max_x - min_x, 1):g},\n"
    f"  height: {round(max_y - min_y, 1):g},\n"
    f"  baseline: {round(-min_y, 1):g},\n"
    f"  capHeight: {font['OS/2'].sCapHeight},\n"
    f'  path: "{svg.getCommands()}",\n'
    "} as const;\n"
)
print(f"{WORD}: {max_x - min_x:.1f} x {max_y - min_y:.1f} units, upem {upem}")
